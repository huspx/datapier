const languageKey = 'datapier.languagePreference';
let languagePreference = 'system';
try {
  const saved = localStorage.getItem(languageKey);
  if (['system', 'zh-CN', 'en'].includes(saved)) languagePreference = saved;
} catch { /* 存储不可用时仍允许本次会话选择语言。 */ }
function systemLanguage() {
  const raw = navigator.languages?.length
    ? navigator.languages[0]
    : navigator.language;
  if (typeof raw !== 'string' || !raw.trim()) return 'en';
  try {
    const locale = new Intl.Locale(raw.trim().replace(/_/g, '-'));
    if (locale.language === 'en') return 'en';
    if (locale.language !== 'zh') return 'en';
    if (locale.script) return locale.script === 'Hans' ? 'zh-CN' : 'en';
    if (locale.region) {
      return ['CN', 'SG'].includes(locale.region)
        ? 'zh-CN'
        : 'en';
    }
    return locale.maximize().script === 'Hans' ? 'zh-CN' : 'en';
  } catch {
    return 'en';
  }
}
let language = languagePreference === 'system'
  ? systemLanguage()
  : languagePreference;
const t = (key, values = {}) => {
  const message = messages[language][key];
  return typeof message === 'string'
    ? message.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''))
    : message;
};
